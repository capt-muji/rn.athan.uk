def t(s):
    m = re.match(r'(\d{1,2}):(\d{2})\s*(am|pm)', s)
    h, mi, ap = int(m[1]), int(m[2]), m[3]
    if ap == 'pm' and h != 12: h += 12
    if ap == 'am' and h == 12: h = 0
    return f"{h:02d}:{mi:02d}"

