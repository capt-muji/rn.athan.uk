        vals = e[3:]
        month = MONTH[mon]
        if month < prev:
            year += 1
        prev = month
        iso = f'{year}-{month:02d}-{day:02d}'
        if iso in rows:
            errors.append(f'duplicate {iso} in {sheet}')
