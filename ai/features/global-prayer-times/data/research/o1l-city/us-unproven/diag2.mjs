import fs from 'fs';
import adhan from '$HOME/athan-gitree/census/adhan-build/node_modules/adhan/lib/cjs/Adhan.js';
const d=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
const lat=+process.argv[3], lng=+process.argv[4], tz=process.argv[5];
const fmt=new Intl.DateTimeFormat('en-GB',{timeZone:tz,hour:'2-digit',minute:'2-digit',hour12:false});
const lm=dt=>{const p=Object.fromEntries(fmt.formatToParts(dt).map(x=>[x.type,x.value]));return (+p.hour%24)*60+(+p.minute);};
const hm=s=>{const[a,b]=s.split(':').map(Number);return a*60+b;};
const p=new adhan.CalculationParameters('Other',15,15,0);
p.madhab=adhan.Madhab.Shafi; p.highLatitudeRule=adhan.HighLatitudeRule.TwilightAngle; p.rounding=adhan.Rounding.None;
const c=new adhan.Coordinates(lat,lng);
const by={};
for(const [date,v] of Object.entries(d.days)){
  if(!date.startsWith('2026')) continue;
  const [y,m,dd]=date.split('-').map(Number);
  const t=new adhan.PrayerTimes(c,new Date(Date.UTC(y,m-1,dd,18,0)),p);
  const k=date.slice(0,7); by[k]=by[k]||{f:[],i:[],s:[],d:[],a:[],mg:[]};
  const g=k=>v[k]!=null?v[k]:v[k+'_athan'];
  const row={}; for(const c of ['fajr','sunrise','dhuhr','asr','maghrib','isha']) row[c]=hm(g(c));
  if(row.dhuhr<row.sunrise) row.dhuhr+=720;
  for(const c of ['asr','maghrib','isha']) if(row[c]<row.dhuhr) row[c]+=720;
  const gg=k=>row[k];
  by[k].f.push(gg('fajr')-lm(t.fajr));
  by[k].i.push(gg('isha')-lm(t.isha));
  by[k].s.push(gg('sunrise')-lm(t.sunrise));
  by[k].d.push(gg('dhuhr')-lm(t.dhuhr));
  by[k].a.push(gg('asr')-lm(t.asr));
  by[k].mg.push(gg('maghrib')-lm(t.maghrib));
}
const med=a=>{const s=[...a].sort((x,y)=>x-y);return s[Math.floor(s.length/2)];};
for(const k of Object.keys(by).sort()) console.log(k,'fajr',med(by[k].f),'sunrise',med(by[k].s),'dhuhr',med(by[k].d),'asr',med(by[k].a),'maghrib',med(by[k].mg),'isha',med(by[k].i));
